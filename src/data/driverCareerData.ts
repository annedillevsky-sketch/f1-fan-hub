export function getDriverDetailedProfile(driverIdOrNameOrCode: string): DriverDetailedProfile | undefined {
  if (!driverIdOrNameOrCode) return undefined;
  const lower = driverIdOrNameOrCode.toLowerCase().trim();

  // Direct ID check
  if (DRIVER_CAREER_DATABASE[lower]) {
    return DRIVER_CAREER_DATABASE[lower];
  }

  // Check code or last name or full name match
  for (const profile of Object.values(DRIVER_CAREER_DATABASE)) {
    if (
      profile.code.toLowerCase() === lower ||
      profile.lastName.toLowerCase() === lower ||
      profile.fullName.toLowerCase().includes(lower) ||
      lower.includes(profile.lastName.toLowerCase()) ||
      lower.includes(profile.code.toLowerCase())
    ) {
      return profile;
    }
  }

  return undefined;
}
